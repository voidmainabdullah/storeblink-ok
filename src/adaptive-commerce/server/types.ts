import type {
  MerchantPatch,
  RuntimeArtifact,
  StoreDefinition,
} from "../contracts";
import type { RuntimeAsset, StorefrontCompilerRegistry } from "../compiler";
import type { AdaptiveQaIssue } from "../qa";
import type {
  LegacyShadowProjection,
  StructuralArtifactDiff,
} from "../shadow";

export const SERVER_COMPILE_JOB_STATES = [
  "claimed",
  "loading-source",
  "compiling",
  "quality-gate",
  "shadowing",
  "publishing",
  "succeeded",
  "failed",
] as const;

export type ServerCompileJobState = (typeof SERVER_COMPILE_JOB_STATES)[number];
export type ServerCompileIntent = "shadow-only" | "publish";

export type ServerCompileJobRequest = Readonly<{
  /** Generated by the trusted server entrypoint, never by compiler output. */
  jobId: string;
  idempotencyKey: string;
  storeId: string;
  installationId: string;
  expectedSourceRevision: number;
  expectedPointerRevision: number;
  intent: ServerCompileIntent;
}>;

export type ServerCompileJobResult = Readonly<{
  jobId: string;
  sourceRevision: number;
  artifactHash: string;
  shadowId: string;
  /**
   * Comparable intentional changes remain pending until a theme.publish
   * reviewer makes an explicit decision. Equal candidates are auto-accepted;
   * opaque legacy output stays uncomparable until trusted visual evidence is
   * attached.
   */
  shadowStatus: "pending" | "accepted" | "rejected" | "uncomparable";
  publicationId: string | null;
  pointerRevision: number | null;
  published: boolean;
}>;

export type ClaimedCompileJob = Readonly<{
  jobId: string;
  state: ServerCompileJobState;
  createdAt: string;
  result: ServerCompileJobResult | null;
  errorCode: string | null;
  errorMessage: string | null;
}>;

export type CompileJobClaim = Readonly<{
  kind: "claimed" | "existing";
  job: ClaimedCompileJob;
}>;

export type CanonicalCompileSource = Readonly<{
  sourceRevision: number;
  sourceHash: string;
  storeDefinition: StoreDefinition;
  merchantPatches: readonly MerchantPatch[];
  assets: readonly RuntimeAsset[];
  legacyProjection: LegacyShadowProjection;
}>;

export type ArtifactReleaseGateResult = Readonly<{
  passed: boolean;
  issues: readonly AdaptiveQaIssue[];
}>;

export interface ArtifactReleaseGate {
  evaluate(input: Readonly<{
    artifact: RuntimeArtifact;
    source: CanonicalCompileSource;
  }>): ArtifactReleaseGateResult | Promise<ArtifactReleaseGateResult>;
}

export interface ServerCompilerGateway {
  claimJob(input: Readonly<{
    request: ServerCompileJobRequest;
    requestHash: string;
  }>): Promise<CompileJobClaim>;
  transitionJob(input: Readonly<{
    jobId: string;
    expectedState: ServerCompileJobState;
    nextState: ServerCompileJobState;
  }>): Promise<void>;
  loadCanonicalSource(input: Readonly<{
    storeId: string;
    installationId: string;
    expectedSourceRevision: number;
  }>): Promise<CanonicalCompileSource>;
  assertSourceRevision(input: Readonly<{
    storeId: string;
    installationId: string;
    expectedSourceRevision: number;
  }>): Promise<void>;
  persistCandidate(input: Readonly<{
    jobId: string;
    expectedState: ServerCompileJobState;
    sourceRevision: number;
    artifact: RuntimeArtifact;
  }>): Promise<void>;
  recordShadow(input: Readonly<{
    jobId: string;
    storeId: string;
    installationId: string;
    artifactHash: string;
    structuralDiff: StructuralArtifactDiff;
    status: "pending" | "accepted" | "rejected" | "uncomparable";
  }>): Promise<string>;
  publishAtomic(input: Readonly<{
    jobId: string;
    storeId: string;
    installationId: string;
    sourceRevision: number;
    artifact: RuntimeArtifact;
    expectedPointerRevision: number;
  }>): Promise<Readonly<{
    publicationId: string;
    pointerRevision: number;
  }>>;
  completeJob(input: Readonly<{
    jobId: string;
    expectedState: ServerCompileJobState;
    result: ServerCompileJobResult;
  }>): Promise<void>;
  failJob(input: Readonly<{
    jobId: string;
    errorCode: string;
    errorMessage: string;
  }>): Promise<void>;
}

export interface ServerCompilerRegistryLoader {
  loadCompilerRegistry(input: Readonly<{
    storeId: string;
    installationId: string;
  }>): Promise<StorefrontCompilerRegistry>;
}

export type ServerCompilerDependencies = Readonly<{
  /** Static registry is intended for certified built-in workers and tests. */
  registry?: StorefrontCompilerRegistry;
  /** Production workers should load the installation's exact released pins. */
  registryLoader?: ServerCompilerRegistryLoader;
  gateway: ServerCompilerGateway;
  releaseGate: ArtifactReleaseGate;
}>;
